"""Джарвис — голосовой ассистент для Ubuntu 24.04 (GNOME, Wayland). Запуск: python3 assistant.py (см. README.md).

Модули:
    app        — цикл Джарвиса: слушать «Джарвис», выполнить, ответить голосом; команды запуска; фоновая служба
    dispatcher — фраза -> модель первого слоя -> нужный исполнитель (или второй слой), отчёт о времени
    parser     — модель первого слоя (папка ml/ проекта: код разбора и веса)
    browser    — сайты, поиск, YouTube, переводчик          apps   — программы, игры, папки, файлы, настройки
    system     — 146 системных действий по доменам          llm    — второй слой: Gemini с инструментами
    sys_query  — безопасные читающие команды для второго слоя
    listen     — микрофон, фраза по паузам, GigaAM, «Джарвис»   speak — голос ответа (Piper / Google)
    spoken     — устная речь: числительные, аббревиатуры, расширения файлов
"""
