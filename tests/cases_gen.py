def _is_question(q):
    return q.split()[0] in {"как", "что", "где", "почему", "сколько", "когда", "кто"}


def site_query_cases(n):
    rng = random.Random(SEED)
    out = []
    while len(out) < n:
        nom, acc, loc, prep, kind = rng.choice(SITES)
        q = _query(rng, kind)
        plain = not _is_question(q)       # «найди <вопрос> на сайте» — спорный случай (правило 7), его не берём
        t = rng.randrange(17)
        if t == 0:   out.append(SQ(f"открой {acc} и найди {q}", acc, q))
        elif t == 1: out.append(SQ(f"открой {acc} найди {q}", acc, q))
        elif t == 2: out.append(SQ(f"зайди {prep} {loc} и поищи {q}", loc, q))
        elif t == 3 and plain: out.append(SQ(f"найди {q} {prep} {loc}", loc, q))
        elif t == 4: out.append(SQ(f"{prep} {loc} найди {q}", loc, q))
        elif t == 5: out.append(SQ(f"джарвис {prep} {loc} поищи мне {q}", loc, q))
        elif t == 6 and plain: out.append(SQ(f"поищи {q} {prep} {loc} пожалуйста", loc, q))
        elif t == 7 and plain: out.append(SQ(f"хочу найти {q} {prep} {loc}", loc, q))
        elif t == 8: out.append(SQ(f"запусти {acc} и ищи {q}", acc, q))
        elif t == 9 and plain: out.append(SQ(f"сделай запрос {q} {prep} {loc}", loc, q))
        elif t == 10 and plain: out.append(SQ(f"вбей {q} {prep} {loc}", loc, q))
        elif t == 11 and plain: out.append(SQ(f"мне нужно найти {q} {prep} {loc}", loc, q))
        elif t == 12: out.append(SQ(f"открой мне {acc} и покажи {q}", acc, q))
        elif t == 13: out.append(SQ(f"окей открой {acc} и поищи там {q}", acc, q, "reach"))
        elif t == 14 and kind in ("music", "video", "movie") and plain:
            verb = rng.choice(["включи", "поставь"])
            out.append(SQ(f"{verb} {q} {prep} {loc}", loc, q))
        elif t == 15 and kind in ("music", "video"):
            out.append(SQ(f"запусти {acc} и включи {q}", acc, q))
        elif t == 16 and kind in ("music", "movie") and plain:
            out.append(SQ(f"хочу послушать {q} {prep} {loc}" if kind == "music" else f"хочу посмотреть {q} {prep} {loc}", loc, q))
    return out


