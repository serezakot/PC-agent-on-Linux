def translate_cases(n):
    rng = random.Random(SEED + 4)
    codes = [c for c in LANG_FORMS if c != "ru"]
    out = []
    while len(out) < n:
        to_ru = rng.random() < 0.12
        code = "ru" if to_ru else ("en" if rng.random() < 0.3 else rng.choice(codes))
        acc, loc, adv = LANG_FORMS[code]
        t = rng.choice(EN_TEXTS if to_ru else RU_TEXTS)
        templ, need_adv, tail = rng.choice(T_TEMPL)
        if need_adv:
            if adv is None:
                continue
            phrase = templ.format(t=t, adv=adv)
            if rng.random() < 0.4:                       # «по-английски» одним словом
                phrase = phrase.replace(f"по {adv}", f"по-{adv}")
        else:
            if "с русского" in templ and to_ru:
                continue
            phrase = templ.format(t=t, acc=acc, loc=loc)
        tag = "translate_tricky" if t in RU_TEXTS[:8] + RU_TEXTS[21:31] else "translate"
        out.append(TR(phrase, t + tail, code, tag))
    return out
